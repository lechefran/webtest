// WebClient is an HTTP client for API testing. Create one with [InitWebClient]
// and configure it with [WebClient.Headers] and [WebClient.Options]. A
// WebClient is safe for concurrent use.
type WebClient struct {
	mu                   sync.RWMutex
	client               http.Client
	headers              map[string]string
	transport            *transport
	options              WebClientOptions
	generatedLogFilePath string
}

const (
	logPrefixHeaders      = "[HEADERS] "
	logPrefixRequest      = "[REQUEST] "
	logPrefixResponse     = "[RESPONSE] "
	defaultRequestTimeout = 30 * time.Second
)

// InitWebClient returns a WebClient with default options and no headers.
func InitWebClient() *WebClient {
	t := newTransport()
	return &WebClient{
		transport: t,
		headers:   nil,
		client: http.Client{
			Transport: t,
		},
		options: WebClientOptions{},
	}
}

func (w *WebClient) newValidatedRequest(method string, rawURL string, body io.Reader) (*http.Request, error) {
	if err := w.validateRequestURL(rawURL); err != nil {
		return nil, err
	}

	//nolint:AIK_go_G107 // URL is validated against the configured allowlist before use.
	// nosec G107 // URL is validated before making the HTTP request.
	req, err := http.NewRequest(method, rawURL, body)
	if err != nil {
		return nil, err
	}

	return req, nil
}

// Get sends a GET request to url.
func (w *WebClient) Get(url string) (*http.Response, error) {
	req, err := w.newValidatedRequest(http.MethodGet, url, nil)
	if err != nil {
		return nil, err
	}

	return w.execute(req, url)
}

// Post sends a POST request to url with body.
func (w *WebClient) Post(url string, body []byte) (*http.Response, error) {
	req, err := w.newValidatedRequest(http.MethodPost, url, bytes.NewBuffer(body))
	if err != nil {
		return nil, err
	}

	return w.execute(req, url)
}

