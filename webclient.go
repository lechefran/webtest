// Headers sets the headers sent with every request, replacing any previously
// set headers. The map is copied; passing nil clears all headers.
func (w *WebClient) Headers(m map[string]string) *WebClient {
	w.mu.Lock()
	defer w.mu.Unlock()

	if m == nil {
		w.headers = nil
		return w
	}
	w.headers = cloneStringMap(m)
	return w
}

// Options replaces the client's options. The value is copied, and passing the
// zero value resets to defaults. Any cached autogenerated log file path is
// cleared.
func (w *WebClient) Options(o WebClientOptions) *WebClient {
	w.mu.Lock()
	defer w.mu.Unlock()

	w.options = cloneWebClientOptions(o)
	w.generatedLogFilePath = ""
	return w
}

// ClearGeneratedLogFilePath makes the next logged request create a fresh
// autogenerated log file without changing any other configuration.
func (w *WebClient) ClearGeneratedLogFilePath() *WebClient {
	w.mu.Lock()
	defer w.mu.Unlock()

	w.generatedLogFilePath = ""
	return w
}

func setHeaders(r *http.Request, m map[string]string) {
	if r == nil || m == nil {
		return
	}
	for k, v := range m {
		r.Header.Set(k, v)
	}
}

func cloneStringMap(m map[string]string) map[string]string {
	if m == nil {
		return nil
	}
	cloned := make(map[string]string, len(m))
	maps.Copy(cloned, m)
	return cloned
}

func cloneWebClientOptions(opts WebClientOptions) WebClientOptions {
	opts.AllowedOrigins = append([]string(nil), opts.AllowedOrigins...)
	return opts
}

type requestOrigin struct {
	scheme string
	host   string
	port   string
}

func parseRequestOrigin(raw string) (requestOrigin, error) {
	parsed, err := url.Parse(raw)
	if err != nil {
		return requestOrigin{}, err
	}
	if !parsed.IsAbs() || parsed.Host == "" || parsed.User != nil {
		return requestOrigin{}, errors.New("must be an absolute HTTP or HTTPS origin without credentials")
	}

	scheme := strings.ToLower(parsed.Scheme)
	if scheme != "http" && scheme != "https" {
		return requestOrigin{}, errors.New("only HTTP and HTTPS origins are allowed")
	}

	host := strings.TrimSuffix(strings.ToLower(parsed.Hostname()), ".")
	if host == "" {
		return requestOrigin{}, errors.New("origin must include a hostname")
	}
	if ip := net.ParseIP(host); ip != nil {
		host = ip.String()
	}

	port := parsed.Port()
	if port == "" {
		if scheme == "https" {
			port = "443"
		} else {
			port = "80"
		}
	} else {
		portNumber, err := strconv.Atoi(port)
		if err != nil || portNumber < 1 || portNumber > 65535 {
			return requestOrigin{}, errors.New("origin port must be between 1 and 65535")
		}
		port = strconv.Itoa(portNumber)
	}

	return requestOrigin{scheme: scheme, host: host, port: port}, nil
}

func parseAllowedOrigins(origins []string) (map[requestOrigin]struct{}, error) {
	allowed := make(map[requestOrigin]struct{}, len(origins))
	for _, raw := range origins {
		parsed, err := url.Parse(raw)
		if err != nil {
			return nil, fmt.Errorf("invalid allowed origin %q: %w", raw, err)
		}
		if (parsed.Path != "" && parsed.Path != "/") || parsed.RawQuery != "" || parsed.ForceQuery || parsed.Fragment != "" {
			return nil, fmt.Errorf("invalid allowed origin %q: paths, queries, and fragments are not allowed", raw)
		}
		origin, err := parseRequestOrigin(raw)
		if err != nil {
			return nil, fmt.Errorf("invalid allowed origin %q: %w", raw, err)
		}
		allowed[origin] = struct{}{}
	}
	return allowed, nil
}

func validateRequestOrigin(raw string, allowed map[requestOrigin]struct{}) error {
	origin, err := parseRequestOrigin(raw)
	if err != nil {
		return fmt.Errorf("invalid request destination: %w", err)
	}
	if _, ok := allowed[origin]; !ok {
		return fmt.Errorf("request destination %q is not in the allowed origins", raw)
	}
	return nil
}

func defaultLogFilePath(now time.Time) string {
	return "./" + now.UTC().Format("20060102T150405Z") + ".log"
}

func formatRequestHeadersForLog(headers http.Header) (string, error) {
	if len(headers) == 0 {
		return "{}", nil
	}
	body, err := json.Marshal(headers)
	if err != nil {
		return "", err
	}
	return string(body), nil
}

func formatRequestBodyForLog(body []byte) (string, error) {
	trimmed := bytes.TrimSpace(body)
	if len(trimmed) == 0 {
		return "{}", nil
	}
	if json.Valid(trimmed) {
		var compact bytes.Buffer
		if err := json.Compact(&compact, trimmed); err != nil {
			return "", err
		}
		return compact.String(), nil
	}

	serialized, err := json.Marshal(map[string]string{"raw": string(body)})
	if err != nil {
		return "", err
	}
	return string(serialized), nil
}

func formatByteSize(n int) string {
	if n < 1024 {
		return fmt.Sprintf("%db", n)
	}
	if n < 1024*1024 {
		return fmt.Sprintf("%.2fKb", float64(n)/1024)
	}
	if n < 1024*1024*1024 {
		return fmt.Sprintf("%.2fMb", float64(n)/(1024*1024))
	}
	return fmt.Sprintf("%.2fGb", float64(n)/(1024*1024*1024))
}

func prepareRequestBodyForLog(req *http.Request) (string, bool, int, error) {
	if req == nil || req.Body == nil || req.Body == http.NoBody {
		return "", false, 0, nil
	}

	bodyBytes, err := io.ReadAll(req.Body)
	if err != nil {
		return "", false, 0, err
	}
	if err := req.Body.Close(); err != nil {
		return "", false, 0, err
	}

	req.Body = io.NopCloser(bytes.NewReader(bodyBytes))
	req.GetBody = func() (io.ReadCloser, error) {
		return io.NopCloser(bytes.NewReader(bodyBytes)), nil
	}

	if len(bytes.TrimSpace(bodyBytes)) == 0 {
		return "", false, len(bodyBytes), nil
	}

	bodyLine, err := formatRequestBodyForLog(bodyBytes)
	if err != nil {
		return "", false, len(bodyBytes), err
	}
	return bodyLine, true, len(bodyBytes), nil
}

func prepareResponseBodyForLog(res *http.Response) (string, bool, int, error) {
	if res == nil || res.Body == nil || res.Body == http.NoBody {
		return "", false, 0, nil
	}

	bodyBytes, err := io.ReadAll(res.Body)
	if err != nil {
		return "", false, 0, err
	}
	if err := res.Body.Close(); err != nil {
		return "", false, 0, err
	}

	// Restore the response body so callers can still read it.
	res.Body = io.NopCloser(bytes.NewReader(bodyBytes))

	if len(bytes.TrimSpace(bodyBytes)) == 0 {
		return "", false, len(bodyBytes), nil
	}

	bodyLine, err := formatRequestBodyForLog(bodyBytes)
	if err != nil {
		return "", false, len(bodyBytes), err
	}
	return bodyLine, true, len(bodyBytes), nil
}

type bodyLogPayload struct {
	line    string
	hasLine bool
	bytes   int
}

type requestTiming struct {
	totalDuration time.Duration
	connDuration  time.Duration
	connReused    bool
}

func shouldPrepareRequestBodyForLog(opts WebClientOptions) bool {
	return opts.WriteToFile && (opts.WriteRequest || opts.LogMetadata)
}

func shouldPrepareResponseBodyForLog(opts WebClientOptions) bool {
	return opts.WriteToFile && (opts.WriteResponse || opts.LogMetadata)
}

func effectiveRequestTimeout(opts WebClientOptions) time.Duration {
	if opts.RequestTimeout > 0 {
		return opts.RequestTimeout
	}
	return defaultRequestTimeout
}

func prepareRequestPayloadForLog(req *http.Request, opts WebClientOptions) (bodyLogPayload, error) {
	if !shouldPrepareRequestBodyForLog(opts) {
		return bodyLogPayload{}, nil
	}

	line, hasLine, bodyBytes, err := prepareRequestBodyForLog(req)
	if err != nil {
		return bodyLogPayload{}, err
	}

	return bodyLogPayload{
		line:    line,
		hasLine: hasLine,
		bytes:   bodyBytes,
	}, nil
}

func prepareResponsePayloadForLog(res *http.Response, opts WebClientOptions) (bodyLogPayload, error) {
	if !shouldPrepareResponseBodyForLog(opts) {
		return bodyLogPayload{}, nil
	}

	line, hasLine, bodyBytes, err := prepareResponseBodyForLog(res)
	if err != nil {
		return bodyLogPayload{}, err
	}

	return bodyLogPayload{
		line:    line,
		hasLine: hasLine,
		bytes:   bodyBytes,
	}, nil
}

func buildCallSummary(
	req *http.Request,
	requestURL string,
	res *http.Response,
	timing requestTiming,
	opts WebClientOptions,
	requestBytes int,
	responseBytes int,
	requestErr error,
) string {
	var summary string
	if requestErr != nil {
		summary = req.Method + " " + requestURL + " ERROR total=" + fmt.Sprintf("%.3fs", timing.totalDuration.Seconds())
	} else if res != nil {
		summary = req.Method + " " + requestURL + " " + res.Status + " total=" + fmt.Sprintf("%.3fs", timing.totalDuration.Seconds())
	} else {
		summary = req.Method + " " + requestURL + " ERROR total=" + fmt.Sprintf("%.3fs", timing.totalDuration.Seconds())
	}

	if timing.connReused {
		summary += " conn=reused"
	} else {
		summary += " connect=" + fmt.Sprintf("%.3fs", timing.connDuration.Seconds())
	}

	if opts.LogMetadata {
		summary += " sent=" + formatByteSize(requestBytes) + " received=" + formatByteSize(responseBytes)
	}

	return summary
}

func printCallSummary(summary string, res *http.Response, requestErr error) {
	if requestErr != nil || res == nil {
		color.HiRed(summary)
		return
	}

	if Is2xxSuccessful(res) {
		color.Green(summary)
		return
	}
	if Is3xxRedirection(res) {
		color.Yellow(summary)
		return
	}
	color.HiRed(summary)
}

func (w *WebClient) resolveLogFilePath(opts WebClientOptions) string {
	if opts.FilePath != "" {
		return opts.FilePath
	}

	w.mu.Lock()
	defer w.mu.Unlock()

	if w.generatedLogFilePath == "" {
		w.generatedLogFilePath = defaultLogFilePath(time.Now())
		color.HiBlue("Application logs will be saved to %s", w.generatedLogFilePath)
	}

	return w.generatedLogFilePath
}

func (w *WebClient) writeRequestLogs(
	opts WebClientOptions,
	req *http.Request,
	callSummary string,
	requestPayload bodyLogPayload,
	responsePayload bodyLogPayload,
) error {
	if !opts.WriteToFile {
		return nil
	}

	fileName := w.resolveLogFilePath(opts)
	for _, part := range strings.Split(filepath.ToSlash(fileName), "/") {
		if part == ".." {
			return fmt.Errorf("invalid log file path: %q", fileName)
		}
	}
	fileName = filepath.Clean(fileName)
	f, err := os.OpenFile(fileName, os.O_APPEND|os.O_CREATE|os.O_WRONLY, 0644)
	if err != nil {
		return err
	}

	if err := writeToFile(f, []byte(callSummary)); err != nil {
		_ = closeFile(f)
		return err
	}

	if opts.WriteHeaders {
		headerLine, err := formatRequestHeadersForLog(req.Header)
		if err != nil {
			_ = closeFile(f)
			return err
		}
		if err := writeToFile(f, []byte(logPrefixHeaders+headerLine)); err != nil {
			_ = closeFile(f)
			return err
		}
	}

	if opts.WriteRequest && requestPayload.hasLine {
		if err := writeToFile(f, []byte(logPrefixRequest+requestPayload.line)); err != nil {
			_ = closeFile(f)
			return err
		}
	}

	if opts.WriteResponse && responsePayload.hasLine {
		if err := writeToFile(f, []byte(logPrefixResponse+responsePayload.line)); err != nil {
			_ = closeFile(f)
			return err
		}
	}

	return closeFile(f)
}

func (w *WebClient) doRequestWithTiming(
	req *http.Request,
	timeout time.Duration,
	allowedOrigins map[requestOrigin]struct{},
) (*http.Response, requestTiming, error) {
	start := time.Now()
	// Trace hooks can fire on net/http's dialer goroutines, possibly after
	// client.Do returns when a pooled connection wins the race, so guard the
	// shared timing state.
	var traceMu sync.Mutex
	var connStart time.Time
	var connDuration time.Duration
	var connReused bool

	trace := &httptrace.ClientTrace{
		ConnectStart: func(_, _ string) {
			traceMu.Lock()
			defer traceMu.Unlock()
			connStart = time.Now()
		},
		ConnectDone: func(_, _ string, err error) {
			traceMu.Lock()
			defer traceMu.Unlock()
			if err != nil || connStart.IsZero() {
				return
			}
			connDuration += time.Since(connStart)
			connStart = time.Time{}
		},
		GotConn: func(info httptrace.GotConnInfo) {
			traceMu.Lock()
			defer traceMu.Unlock()
			connReused = info.Reused
		},
	}

	tracedReq := req.WithContext(httptrace.WithClientTrace(req.Context(), trace))
	client := w.client
	client.Timeout = timeout
	if allowedOrigins != nil {
		previousCheckRedirect := client.CheckRedirect
		client.CheckRedirect = func(redirectReq *http.Request, via []*http.Request) error {
			if previousCheckRedirect != nil {
				if err := previousCheckRedirect(redirectReq, via); err != nil {
					return err
				}
			} else if len(via) >= 10 {
				return errors.New("stopped after 10 redirects")
			}

			return validateRequestOrigin(redirectReq.URL.String(), allowedOrigins)
		}
	}
	res, err := client.Do(tracedReq)
	traceMu.Lock()
	timing := requestTiming{
		totalDuration: time.Since(start),
		connDuration:  connDuration,
		connReused:    connReused,
	}
	traceMu.Unlock()

	if err != nil {
		return res, timing, err
	}
	return res, timing, nil
}

func (w *WebClient) snapshotConfig() (map[string]string, WebClientOptions) {
	w.mu.RLock()
	defer w.mu.RUnlock()

	return cloneStringMap(w.headers), cloneWebClientOptions(w.options)
}

// Is2xxSuccessful reports whether r has a 2xx status code. It returns false
// for a nil response.
func Is2xxSuccessful(r *http.Response) bool {
	if r == nil {
		return false
	}
	status := r.StatusCode
	return status >= 200 && status <= 299
}

// Is3xxRedirection reports whether r has a 3xx status code. It returns false
// for a nil response.
func Is3xxRedirection(r *http.Response) bool {
	if r == nil {
		return false
	}
	status := r.StatusCode
	return status >= 300 && status <= 399
}

// Is4xxClientError reports whether r has a 4xx status code. It returns false
// for a nil response.
func Is4xxClientError(r *http.Response) bool {
	if r == nil {
		return false
	}
	status := r.StatusCode
	return status >= 400 && status <= 499
}

// Is5xxServerError reports whether r has a 5xx status code. It returns false
// for a nil response.
func Is5xxServerError(r *http.Response) bool {
	if r == nil {
		return false
	}
	status := r.StatusCode
	return status >= 500 && status <= 599
}

func (w *WebClient) execute(req *http.Request, url string) (*http.Response, error) {
	if req == nil {
		return nil, errors.New("request cannot be nil")
	}
	headers, opts := w.snapshotConfig()
	var allowedOrigins map[requestOrigin]struct{}
	if len(opts.AllowedOrigins) > 0 {
		var err error
		allowedOrigins, err = parseAllowedOrigins(opts.AllowedOrigins)
		if err != nil {
			return nil, err
		}
		if err := validateRequestOrigin(req.URL.String(), allowedOrigins); err != nil {
			return nil, err
		}
	}
	setHeaders(req, headers)

	requestPayload, err := prepareRequestPayloadForLog(req, opts)
	if err != nil {
		return nil, err
	}

	res, timing, err := w.doRequestWithTiming(req, effectiveRequestTimeout(opts), allowedOrigins)
	if err != nil {
		summary := buildCallSummary(req, url, res, timing, opts, requestPayload.bytes, 0, err)
		printCallSummary(summary, res, err)
		logErr := w.writeRequestLogs(opts, req, summary, requestPayload, bodyLogPayload{})
		if logErr != nil {
			return res, errors.Join(err, logErr)
		}
		return res, err
	}

	responsePayload, err := prepareResponsePayloadForLog(res, opts)
	if err != nil {
		return res, err
	}

	summary := buildCallSummary(req, url, res, timing, opts, requestPayload.bytes, responsePayload.bytes, nil)
	printCallSummary(summary, res, nil)

	if err := w.writeRequestLogs(opts, req, summary, requestPayload, responsePayload); err != nil {
		return res, err
	}

	return res, nil
}

func (w *WebClient) validateRequestURL(raw string) error {
	_, opts := w.snapshotConfig()
	if len(opts.AllowedOrigins) == 0 {
		return nil
	}
	allowedOrigins, err := parseAllowedOrigins(opts.AllowedOrigins)
	if err != nil {
		return err
	}
	return validateRequestOrigin(raw, allowedOrigins)
}

// CloseIdleConnections closes any idle keep-alive connections held by the
// client's connection pool.
func (w *WebClient) CloseIdleConnections() {
	w.client.CloseIdleConnections()
}

// CloseResponse closes the body of res. It is a no-op for a nil response or
// body.
func (w *WebClient) CloseResponse(res *http.Response) error {
	if res == nil || res.Body == nil {
		return nil
	}
	if err := res.Body.Close(); err != nil {
		return err
	}
	return nil
}

// AddQueryParams returns s with the key/value pairs in m added to its query
// string. Existing parameters are kept, and the result is encoded with keys in
// sorted order.
func (w *WebClient) AddQueryParams(s string, m map[string]string) (string, error) {
	parsed, err := url.Parse(s)
	if err != nil {
		return "", err
	}

	q := parsed.Query()
	for k, v := range m {
		q.Add(k, v)
	}
	parsed.RawQuery = q.Encode()
	return parsed.String(), nil
}
